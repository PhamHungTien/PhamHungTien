import sharp from 'sharp';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { resolve } from 'node:path';

const sources = new Set();
for (const file of ['src/data/products.ts', 'src/data/storeArtwork.ts']) {
  const code = await readFile(file, 'utf8');
  for (const match of code.matchAll(/from ['"]\.\.\/\.\.\/([^'"]+\.(?:png|jpe?g|webp))['"]/g))
    sources.add(match[1]);
}
for (const name of [
  'setting-bogo.jpg',
  'menubar.png',
  'picker.jpg',
  'setting-clipboard.jpg',
  'setting-phimtat.jpg',
])
  sources.add(`PHTV/public/assets/latest/${name}`);
const imports = [],
  entries = [],
  report = [];
await mkdir('public/media', { recursive: true });
let index = 0;
for (const source of sources) {
  const buffer = await readFile(source);
  const hash = createHash('sha256').update(buffer).digest('hex').slice(0, 16);
  const meta = await sharp(buffer).metadata();
  const icon = /(?:icon|favicon)\./.test(source);
  const widths = [
    ...new Set((icon ? [64, 128, 256] : [320, 640, 960, 1440]).map((w) => Math.min(w, meta.width))),
  ];
  const phtv = source.startsWith('PHTV/public/');
  const output = phtv ? 'PHTV/public/assets/optimized' : 'public/media';
  const url = phtv ? '/PHTV/assets/optimized' : '/media';
  await mkdir(output, { recursive: true });
  const variants = [];
  for (const width of widths) {
    const file = `${hash}-${width}.webp`;
    await sharp(buffer)
      .resize({ width, withoutEnlargement: true })
      .webp({ quality: icon ? 90 : 86, effort: 6 })
      .toFile(`${output}/${file}`);
    variants.push(`${url}/${file} ${width}w`);
  }
  const preferred = widths.find((w) => w >= (icon ? 128 : 960)) ?? widths.at(-1);
  const data = {
    width: meta.width,
    height: meta.height,
    src: `${url}/${hash}-${preferred}.webp`,
    srcSet: variants.join(', '),
  };
  if (source.startsWith('PHTV/public/'))
    entries.push(
      `${JSON.stringify('/PHTV/' + source.slice('PHTV/public/'.length))}: ${JSON.stringify(data)}`,
    );
  else {
    imports.push(`import image${index} from ${JSON.stringify('../../' + source)};`);
    entries.push(`[image${index++}]: ${JSON.stringify(data)}`);
  }
  const optimized = (await readFile(`${output}/${hash}-${preferred}.webp`)).length;
  report.push({ source, originalBytes: buffer.length, optimizedBytes: optimized, widths });
}
await writeFile(
  'src/data/responsiveImages.generated.ts',
  `// Generated by npm run images. Do not edit by hand.\n${imports.join('\n')}\nexport const responsiveImages: Record<string, { width:number; height:number; src:string; srcSet:string }> = {\n${entries.join(',\n')}\n};\n`,
);
await writeFile('docs/image-optimization.json', JSON.stringify(report, null, 2) + '\n');
console.log(
  `Generated responsive WebP variants for ${report.length} images. Original zoom assets are preserved.`,
);
