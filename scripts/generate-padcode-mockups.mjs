// Device presentation only: source screenshots are retained without retouching.
import sharp from 'sharp';
import { readFile, writeFile } from 'node:fs/promises';
const dir = 'PadCodeAI/assets/current/v2';
const svg = (w, h, body) =>
  Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}">${body}</svg>`);
async function device(name, width) {
  const input = await readFile(`${dir}/${name}.webp`);
  const meta = await sharp(input).metadata();
  const height = Math.round((width * meta.height) / meta.width),
    pad = Math.round(width * 0.024),
    radius = Math.round(width * 0.07);
  const screen = await sharp(input)
    .resize(width, height)
    .composite([
      {
        input: svg(
          width,
          height,
          `<rect width="${width}" height="${height}" rx="${radius}" fill="white"/>`,
        ),
        blend: 'dest-in',
      },
    ])
    .png()
    .toBuffer();
  const w = width + pad * 2,
    h = height + pad * 2;
  const frame = svg(
    w,
    h,
    `<rect x="1" y="1" width="${w - 2}" height="${h - 2}" rx="${radius + pad}" fill="#202327" stroke="#737a82" stroke-width="2"/>`,
  );
  return {
    input: await sharp(frame)
      .composite([{ input: screen, left: pad, top: pad }])
      .png()
      .toBuffer(),
    w,
    h,
  };
}
const ipad = await device('ipad-editor', 850),
  phone = await device('iphone-editor', 360);
const w = 1600,
  h = 1400;
await sharp(
  svg(
    w,
    h,
    `<rect width="1600" height="1400" rx="48" fill="#eef1f5"/><ellipse cx="715" cy="1270" rx="570" ry="35" fill="#c5ccd6" opacity=".55"/>`,
  ),
)
  .composite([
    { input: ipad.input, left: 90, top: 60 },
    { input: phone.input, left: 1130, top: 390 },
  ])
  .webp({ quality: 94, effort: 6 })
  .toFile(`${dir}/hero-devices.webp`);
for (const name of [
  'ipad-editor',
  'iphone-editor',
  'ipad-premium',
  'iphone-premium',
  'onboarding',
]) {
  const d = await device(name, name.startsWith('iphone') ? 520 : 860);
  const outer = 54;
  await sharp(
    svg(
      d.w + outer * 2,
      d.h + outer * 2,
      `<rect width="100%" height="100%" rx="32" fill="#eef1f5"/>`,
    ),
  )
    .composite([{ input: d.input, left: outer, top: outer }])
    .webp({ quality: 94, effort: 6 })
    .toFile(`${dir}/${name}-mockup.webp`);
}
